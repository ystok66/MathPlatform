from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any


ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "packages" / "schemas" / "status_catalog.ts"

if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from apps.api.app.statuses import status_catalog  # noqa: E402


def _ts_union(values: list[str]) -> str:
    if not values:
        return "never"
    return " | ".join(json.dumps(value, ensure_ascii=False) for value in values)


def render_status_catalog_types(catalog: dict[str, Any] | None = None) -> str:
    payload = catalog or status_catalog()
    domains = [str(row["domain"]) for row in payload.get("domains", [])]
    severities = sorted(
        {
            str(status.get("severity") or "neutral")
            for domain in payload.get("domains", [])
            for status in domain.get("statuses", [])
        }
    )
    values_by_domain = {
        str(domain["domain"]): [str(status["value"]) for status in domain.get("statuses", [])]
        for domain in payload.get("domains", [])
    }
    catalog_json = json.dumps(payload, ensure_ascii=False, indent=2, sort_keys=True)
    values_json = json.dumps(values_by_domain, ensure_ascii=False, indent=2, sort_keys=True)
    return "\n".join(
        [
            "/* Auto-generated by scripts/dev/generate_status_types.py. Do not edit manually. */",
            "",
            f"export const STATUS_CATALOG = {catalog_json} as const;",
            "",
            f"export const STATUS_VALUES_BY_DOMAIN = {values_json} as const;",
            "",
            "export type StatusCatalog = typeof STATUS_CATALOG;",
            f"export type StatusDomain = {_ts_union(domains)};",
            f"export type StatusSeverity = {_ts_union(severities)};",
            "export type StatusCatalogDomain = StatusCatalog[\"domains\"][number];",
            "export type StatusCatalogItem = StatusCatalogDomain[\"statuses\"][number];",
            "export type StatusValueByDomain = typeof STATUS_VALUES_BY_DOMAIN;",
            "export type StatusValue<D extends StatusDomain> = StatusValueByDomain[D][number];",
            "",
            "export function statusDomain(domain: StatusDomain) {",
            "  return STATUS_CATALOG.domains.find((row) => row.domain === domain);",
            "}",
            "",
            "export function statusMeta<D extends StatusDomain>(domain: D, value: StatusValue<D>) {",
            "  return statusDomain(domain)?.statuses.find((row) => row.value === value);",
            "}",
            "",
        ]
    )


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate TypeScript status catalog types from backend status_catalog().")
    parser.add_argument("--check", action="store_true", help="Exit non-zero if the generated file is stale.")
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args()

    rendered = render_status_catalog_types()
    if args.check:
        current = args.output.read_text(encoding="utf-8") if args.output.exists() else ""
        if current != rendered:
            print(f"stale status catalog types: {args.output}", file=sys.stderr)
            return 1
        return 0
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(rendered, encoding="utf-8", newline="\n")
    try:
        display_path = args.output.resolve().relative_to(ROOT)
    except ValueError:
        display_path = args.output.name
    print(f"wrote {display_path.as_posix() if isinstance(display_path, Path) else display_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
